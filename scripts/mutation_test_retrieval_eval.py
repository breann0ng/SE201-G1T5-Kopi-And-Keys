"""Mutation testing for the retrieval, topic-card and evaluation modules, reusing Tasha's engine in scripts/mutation_test.py.

The mutants are generated by scripts/mutation_test.py (same operators, same skipped code: docstrings,
annotations, main()/__main__ blocks, exception classes). This wrapper only changes how they run:

- each target module has its own test list, so a mutant runs only the tests that exercise it;
- each worker gets a private copy of backend/, scripts/ and tests/ (so mutants of
  scripts/scraping/chunk.py are picked up too); data/ and frontend/ are shared read-mostly
  through a link (a directory junction on Windows, a symlink elsewhere), which is removed
  before the copy is deleted so the real folders are never touched;
- string mutants can turn a path like "chroma" into "XXchromaXX" and create that folder in
  the shared data/; new top-level data/ entries whose name starts with "XX" are removed at
  the end and any other new entry is reported.

Usage (repo root, project venv):
    python scripts/mutation_test_retrieval_eval.py                       # every target
    python scripts/mutation_test_retrieval_eval.py --only stats compare  # targets whose path contains these
    python scripts/mutation_test_retrieval_eval.py --list                # count mutants only
    python scripts/mutation_test_retrieval_eval.py --json out.json       # all mutants and results

Results and how to read them: docs/testing-retrieval-and-evaluation.md.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
from concurrent.futures import ThreadPoolExecutor
from dataclasses import asdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import mutation_test as engine  # noqa: E402  (Tasha's mutant generator)

TIMEOUT_SECONDS = 120
T = "tests/"
TOPIC_CARD_TESTS = [T + "test_topic_cards.py", T + "test_topic_cards_amount_fields.py",
                    T + "test_topic_cards_rules.py", T + "test_topic_card_component.py"]
TARGETS = {
    "backend/kopi_keys/evaluation/stats.py": [T + "test_eval_stats.py", T + "test_eval_compare.py"],
    "backend/kopi_keys/evaluation/compare.py": [T + "test_eval_stats.py", T + "test_eval_compare.py"],
    "backend/kopi_keys/evaluation/retrieval_report.py": [T + "test_eval_relaxed_evidence.py",
                                                          T + "test_retrieval_report.py"],
    "backend/kopi_keys/components/topic_cards.py": TOPIC_CARD_TESTS + [T + "test_profile_scope.py"],
    "backend/kopi_keys/topic_cards.py": TOPIC_CARD_TESTS + [T + "test_discovery_connections.py",
                                                            T + "test_overview.py"],
    "backend/kopi_keys/components/policy_index.py": [
        T + "test_policy_vectors.py", T + "test_snapshot_retriever.py", T + "test_gpu_engine.py"],
    "backend/kopi_keys/components/policy_retrieval.py": [
        T + "test_snapshot_retriever.py", T + "test_policy_vectors.py", T + "test_policy_advisor.py",
        T + "test_discovery_connections.py", T + "test_overview.py"],
    "scripts/scraping/chunk.py": [T + "test_chunking.py"],
}
COPIED = ("backend", "scripts", "tests")
LINKED = ("data", "frontend")


def _link(link: Path, target: Path) -> None:
    if os.name == "nt":  # junctions need no admin rights or developer mode
        subprocess.run(["cmd", "/c", "mklink", "/J", str(link), str(target)], check=True, capture_output=True)
    else:
        link.symlink_to(target, target_is_directory=True)


def make_workspace() -> Path:
    work = Path(tempfile.mkdtemp(prefix="mut-sandra-"))
    ignore = shutil.ignore_patterns("__pycache__", "*.egg-info", ".pytest_cache")
    for name in COPIED:
        shutil.copytree(ROOT / name, work / name, ignore=ignore)
    for name in LINKED:
        _link(work / name, ROOT / name)
    shutil.copy(ROOT / "pyproject.toml", work / "pyproject.toml")
    return work


def drop_workspace(work: Path) -> None:
    for name in LINKED:
        link = work / name
        if os.path.lexists(link):
            os.unlink(link) if link.is_symlink() else os.rmdir(link)  # the link only, never the target
    shutil.rmtree(work, ignore_errors=True)


def run_tests(work: Path, tests: list[str]) -> int:
    env = {**os.environ, "PYTHONPATH": str(work / "backend"), "PYTHONDONTWRITEBYTECODE": "1"}
    command = [sys.executable, "-m", "pytest", "-x", "-q", "-p", "no:cacheprovider", *tests]
    try:
        return subprocess.run(command, cwd=work, env=env, capture_output=True, timeout=TIMEOUT_SECONDS).returncode
    except subprocess.TimeoutExpired:
        return -1


def clean_data(before: set[str]) -> None:
    for name in sorted({p.name for p in (ROOT / "data").iterdir()} - before):
        path = ROOT / "data" / name
        if name.startswith("XX"):
            shutil.rmtree(path) if path.is_dir() else path.unlink()
            print(f"removed data/{name} (created by a string mutant)")
        else:
            print(f"WARNING: new entry data/{name} appeared during the run; check it")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--list", action="store_true", help="count mutants, don't run tests")
    parser.add_argument("--only", nargs="*", help="only targets whose path contains one of these")
    parser.add_argument("--jobs", type=int, default=max(1, (os.cpu_count() or 2) // 2))
    parser.add_argument("--json", type=Path, help="write all mutants and results here")
    args = parser.parse_args()

    targets = {k: v for k, v in TARGETS.items() if not args.only or any(s in k for s in args.only)}
    mutants = [m for path in targets for m in engine.collect(path)]
    for number, (mutant, _) in enumerate(mutants, start=1):
        mutant.id = number
    for path in targets:
        print(f"{path}: {sum(m.file == path for m, _ in mutants)} mutants")
    print(f"total {len(mutants)}", flush=True)
    if args.list:
        return

    before = {p.name for p in (ROOT / "data").iterdir()}
    workspaces = [make_workspace() for _ in range(args.jobs)]
    try:
        for path, tests in targets.items():
            if run_tests(workspaces[0], tests) != 0:
                raise SystemExit(f"Tests for {path} fail before any mutation; fix them first.")
        free, done, start = list(workspaces), [0], time.time()

        def run(item):
            mutant, source = item
            work = free.pop()
            target = work / mutant.file
            original = (ROOT / mutant.file).read_text(encoding="utf-8")
            try:
                target.write_text(source, encoding="utf-8")
                code = run_tests(work, targets[mutant.file])
                mutant.status = "survived" if code == 0 else ("timeout" if code == -1 else "killed")
            finally:
                target.write_text(original, encoding="utf-8")
                free.append(work)
                done[0] += 1
                if done[0] % 50 == 0:
                    print(f"  {done[0]}/{len(mutants)} in {time.time() - start:.0f}s", flush=True)
            return mutant

        with ThreadPoolExecutor(max_workers=args.jobs) as pool:
            results = list(pool.map(run, mutants))
    finally:
        for work in workspaces:
            drop_workspace(work)
        clean_data(before)

    killed = sum(m.status != "survived" for m in results)
    print(f"\nMutation score: {killed}/{len(results)} killed = {100 * killed / max(1, len(results)):.1f}%")
    for path in targets:
        part = [m for m in results if m.file == path]
        dead = sum(m.status != "survived" for m in part)
        print(f"  {path}: {dead}/{len(part)} = {100 * dead / max(1, len(part)):.1f}%")
    survivors = [m for m in results if m.status == "survived"]
    print(f"\n{len(survivors)} survivors:")
    for m in survivors:
        print(f"  #{m.id:4d} {Path(m.file).name}:{m.line} [{m.operator}] {m.original!r} -> {m.mutated!r}")
    if args.json:
        args.json.write_text(json.dumps([asdict(m) for m in results], indent=2), encoding="utf-8")


if __name__ == "__main__":
    main()
